    private void btnAplicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAplicarActionPerformed
        // TODO add your handling code here:
        if(Desde.getDate() == null || Hasta.getDate() == null){
            javax.swing.JOptionPane.showConfirmDialog(this, "Seleccione ambas fechas");
            return;
        }
        fechaDesde = Desde.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
        fechaHasta = Hasta.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        if(fechaDesde.isAfter(fechaHasta)){
            javax.swing.JOptionPane.showConfirmDialog(this, "La fecha Desde no puede ser mayor a la fecha Hasta");
            return;
        }
        actualizarDashboard(fechaDesde, fechaHasta);
    }//GEN-LAST:event_btnAplicarActionPerformed
    
    private void actualizarDashboard(LocalDate Desde, LocalDate Hasta) {
        OrdenServicioDAO ordenDAO = new OrdenServicioDAO();
        ServicioDAO servicioDAO = new ServicioDAO();
        RepuestoDAO repuestoDAO = new RepuestoDAO();

        int totalOrdenes = ordenDAO.contarOrdenes(Desde, Hasta);
        double totalIngresos = ordenDAO.sumarIngresos(Desde, Hasta);
        int totalVehiculo = ordenDAO.contarVehiculosAtendidos(Desde, Hasta);
        int totalServicios = servicioDAO.contarServiciosRealizados(Desde, Hasta);
        int totalRepuestos = repuestoDAO.contarServiciosRealizados(Desde, Hasta);

        txtValorOrdenes.setText(String.valueOf(totalOrdenes));
        txtValorIngresos.setText(String.format("$%,.2f", totalIngresos));
        txtValorVehiculos.setText(String.valueOf(totalVehiculo));
        txtValorServicios.setText(String.valueOf(totalServicios));
        txtValorRepuestos.setText(String.valueOf(totalRepuestos));
    }
