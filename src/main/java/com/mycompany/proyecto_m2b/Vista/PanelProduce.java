    public void editarProduce() {
        if (produceTabla == null) {
            JOptionPane.showMessageDialog(this, "Tiene que seleccionar un residuo de la tabla historial para continuar");
            return;
        }
        String textoCantidad = TXTCantidad.getText().trim();
        if (textoCantidad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar la nueva cantidad");
            return;
        }
        int cantidadNueva;
        try {
            cantidadNueva = Integer.parseInt(textoCantidad);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,"La cantidad no respeta el formato establecido");
            return;
        }
        if (cantidadNueva <= 0) {
            JOptionPane.showMessageDialog(this, "Debe ser mayor a cero");
            return;
        }
        ProduceDAO produceDAO = new ProduceDAO();
        boolean exito = produceDAO.editarProduceAnterior(produceTabla.getId_produccion(), produceTabla.getId_residuos(), produceTabla.getCant_gene(), cantidadNueva);
        if (!exito) {
            JOptionPane.showMessageDialog(this, "No se pudo modificar la cantidad, revise el máximo permitido del residuo");
            return;
        }
        JOptionPane.showMessageDialog(this, "Cantidad modificada correctamente.");
        String idOrden = produceTabla.getId_orden_serv();
        produceTabla = null;
        TXTCantidad.setText("");
        ComboOrdenesServicio.setEnabled(true);
        ComboResiduos.setEnabled(true);
        cargarHistorialProduce(idOrden);
    }
    
    
