    private void seleccionarOrden(JComboBox<?> combo, String idOrden) {
        if (idOrden==null){
            combo.setSelectedIndex(0);
        }
        else{
            for (int i=0; i < combo.getItemCount(); i++){
                Object orden = combo.getItemAt(i);
                if (orden !=null && orden.toString().equalsIgnoreCase(idOrden.trim())){
                    combo.setSelectedIndex(i);
                    return;
                }
            }
            System.out.println("No se encontro el comboBox de ordenes de servicio");
        }
    }
