    private void cargarServicios() {
        DefaultTableModel modelo = new DefaultTableModel(new Object[]{"Código", "Nombre", "Precio"}, 0) {
            public boolean isCellEditable(int r, int c) {
                return false;
            }
        };
        talbagreServi.setModel(modelo);
        listaCompleta = new ServicioDAO().listarServicio();
        for (Servicio s : listaCompleta) {
            modelo.addRow(new Object[]{s.getId_servi(), s.getNom_servicio(), s.getPrecio_del_servicio()});
        }
        txtCantidad.setText("1");
    }
    
    private void filtrarServicios(String texto) {
        DefaultTableModel modelo = (DefaultTableModel) talbagreServi.getModel();
        modelo.setRowCount(0);
        String filtro = texto.trim().toLowerCase();
        for (Servicio s : listaCompleta) {
            if (filtro.isEmpty() || s.getNom_servicio().toLowerCase().contains(filtro)) {
                modelo.addRow(new Object[]{s.getId_servi(), s.getNom_servicio(), s.getPrecio_del_servicio()});
            }
        }
    }
    
