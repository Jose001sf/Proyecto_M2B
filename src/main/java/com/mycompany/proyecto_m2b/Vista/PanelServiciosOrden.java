    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
    int fila = talbagreServi.getSelectedRow();
    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un servicio.");
        return;
    }

    int cantidad;
    try {
        cantidad = Integer.parseInt(txtCantidad.getText().trim());
        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida (ejemplo: 1).");
        return;
    }

    String id = (String) talbagreServi.getValueAt(fila, 0);
    servicioSeleccionado = listaCompleta.stream().filter(s -> s.getId_servi().equals(id)).findFirst().orElse(null);
    cantidadSeleccionada = cantidad;
    aceptado = true;
    javax.swing.SwingUtilities.getWindowAncestor(this).dispose();
    }//GEN-LAST:event_btnAceptarActionPerformed


